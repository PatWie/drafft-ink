//! Generates one `#[test]` per scenario file: `tests/scenarios/<family>/<name>.json` becomes
//! `scenarios::<family>::<name>` in `tests/scenarios.rs`. Adding a file adds a test; no Rust edit.

use std::collections::BTreeSet;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn ident(name: &str) -> String {
    let mut out: String =
        name.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '_' }).collect();
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

fn sorted_entries(dir: &Path) -> Result<Vec<fs::DirEntry>, Box<dyn Error>> {
    let mut entries = fs::read_dir(dir)?.collect::<Result<Vec<_>, _>>()?;
    entries.sort_by_key(fs::DirEntry::file_name);
    Ok(entries)
}

fn main() -> Result<(), Box<dyn Error>> {
    let manifest = std::env::var("CARGO_MANIFEST_DIR")?;
    let root = Path::new(&manifest).join("../../tests/scenarios");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut out = String::from("// @generated by build.rs from tests/scenarios. Do not edit.\n");
    let mut families = BTreeSet::new();
    if root.is_dir() {
        for family in sorted_entries(&root)? {
            let path = family.path();
            let fname = family.file_name().to_string_lossy().into_owned();
            if !path.is_dir() {
                if path.extension().is_some_and(|e| e == "json") {
                    return Err(format!("tests/scenarios/{fname}: scenario files belong in a family directory, tests/scenarios/<family>/{fname}").into());
                }
                continue;
            }
            let fam = ident(&fname);
            if !families.insert(fam.clone()) {
                return Err(format!(
                    "tests/scenarios/{fname}: another directory has the same test module name `{fam}`"
                )
                .into());
            }
            let mut names = BTreeSet::new();
            let mut body = String::new();
            for file in sorted_entries(&path)? {
                let p = file.path();
                if p.extension().is_none_or(|e| e != "json") {
                    continue;
                }
                let stem = p.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
                let name = ident(&stem);
                if !names.insert(name.clone()) {
                    return Err(format!(
                        "tests/scenarios/{fname}/{stem}.json: another file has the same test name `{name}`"
                    )
                    .into());
                }
                writeln!(
                    body,
                    "    #[test]\n    fn {name}() {{\n        drafftink_testkit::scenario::run_file_or_panic(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/../../tests/scenarios/{fname}/{stem}.json\"));\n    }}"
                )?;
            }
            if !body.is_empty() {
                write!(out, "pub mod {fam} {{\n{body}}}\n")?;
            }
        }
    }
    fs::write(Path::new(&std::env::var("OUT_DIR")?).join("scenarios.rs"), out)?;
    Ok(())
}
