/// The colour named `name` (`"blue-500"`), ignoring case. `None` for anything else.
pub fn lookup(name: &str) -> Option<Color> {
    let (family, shade) = name.trim().rsplit_once('-')?;
    let shade: u16 = shade.parse().ok()?;
    let col = SHADES.iter().position(|s| *s == shade)?;
    let f = FAMILIES.iter().find(|f| f.name.eq_ignore_ascii_case(family))?;
    let (r, g, b) = *f.shades.get(col)?;
    Some(Color::rgb(r, g, b))
}

/// The family names, for messages.
pub fn family_names() -> Vec<&'static str> {
    FAMILIES.iter().map(|f| f.name).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_resolve() {
        assert_eq!(lookup("indigo-500"), Some(Color::rgb(0x63, 0x66, 0xf1)));
        assert_eq!(lookup("Blue-100"), Some(Color::rgb(219, 234, 254)));
        assert_eq!(lookup("blue-900").map(Color::to_hex).as_deref(), Some("#1e3a8a"));
        assert_eq!(lookup("blue-123"), None);
        assert_eq!(lookup("mauve-500"), None);
        assert_eq!(lookup("blue"), None);
        assert_eq!(lookup("-500"), None);
        assert_eq!(lookup(""), None);
    }

    #[test]
    fn table_is_complete_and_ordered() {
        assert_eq!(FAMILIES.len(), 22);
        for f in FAMILIES {
            for w in f.shades.windows(2) {
                let lum = |s: (u8, u8, u8)| u32::from(s.0) * 3 + u32::from(s.1) * 6 + u32::from(s.2);
                assert!(lum(w[0]) >= lum(w[1]), "{} gets lighter at a darker shade", f.name);
            }
        }
    }
}
